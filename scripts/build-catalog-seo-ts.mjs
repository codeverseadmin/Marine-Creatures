import fs from 'fs';

const seoData = JSON.parse(fs.readFileSync('scripts/generated-seo-data.json', 'utf8'));

const tsCode = `// Autogenerated Authoritative Full-Catalog SEO Configuration for Marine Creatures
// Phase: SEO-1B — Comprehensive Catalog Optimization

export interface ProductSeoRecord {
  id: string;
  name: string;
  scientificName: string;
  brand: string;
  model: string;
  category: string;
  categoryLabel: string;
  subcategory: string;
  productType: string;
  primaryIntent: string;
  secondaryIntents: string[];
  seoTitle: string;
  metaDescription: string;
  h1: string;
  canonical: string;
  imageStatus: string;
  imageFile: string;
  imageAlt: string;
  researchStatus: string;
  serviceLink: string;
  serviceText: string;
  relatedProductIds: string[];
  hasCareGuide: boolean;
  hasInstallationGuide: boolean;
  specsCount: number;
}

export const CATALOG_SEO_MAP: Record<string, ProductSeoRecord> = ${JSON.stringify(
  seoData.reduce((acc, cur) => {
    acc[cur.id] = cur;
    return acc;
  }, {}),
  null,
  2
)};

export function getProductSeoData(productId: string): ProductSeoRecord | undefined {
  return CATALOG_SEO_MAP[productId];
}
`;

fs.writeFileSync('lib/seo/catalogSeoData.ts', tsCode, 'utf8');
console.log('Successfully written lib/seo/catalogSeoData.ts');
